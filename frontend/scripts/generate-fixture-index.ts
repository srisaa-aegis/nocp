/**
 * Regenerates src/testing/fixture-index.ts: a static import of EVERY JSON file under
 * public/assets/data, keyed by its asset path, so unit tests serve the real fixtures.
 *   npm run fixtures:index
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = join(__dirname, '..');
const DATA = join(ROOT, 'public', 'assets', 'data');

function walk(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : name.endsWith('.json') ? [p] : [];
    });
}

const files = walk(DATA);
const ident = (rel: string) =>
  'f' +
  rel
    .replace(/\.json$/, '')
    .split(/[\/\-_.]/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join('');

const lines = [
  '// GENERATED by scripts/generate-fixture-index.ts (npm run fixtures:index) — do not edit.',
];
const entries: string[] = [];
for (const f of files) {
  const rel = relative(DATA, f).split('\\').join('/');
  const id = ident(rel);
  lines.push(`import ${id} from '../../public/assets/data/${rel}';`);
  entries.push(`  'assets/data/${rel}': ${id},`);
}
lines.push('', 'export const FIXTURES: Record<string, unknown> = {', ...entries, '};', '');
writeFileSync(join(ROOT, 'src', 'testing', 'fixture-index.ts'), lines.join('\n'));
console.log(`${files.length} fixtures indexed`);
